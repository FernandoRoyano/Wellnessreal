import { expect, test } from '@playwright/test'
import { fixtureSession } from '../fixtures/community-session'

test.beforeEach(async ({ page, context, request }) => {
  test.skip(process.env.COMMUNITY_LOCAL_FIXTURE !== '1', 'Solo servicios y cuentas ficticios locales')
  await request.post('http://127.0.0.1:54329/__workout-failure', { data: { mode: '' } })
  await context.route('https://**/*', route => route.abort())
  await context.addInitScript(() => { localStorage.setItem('wr_cookie_consent_v2', 'rejected'); localStorage.setItem('wr_lead_submitted', '1') })
  await fixtureSession(context, 'free')
  await page.goto('/comunidad/mi-semana')
})

test('weekly choices survive reload, stay private to the account and can be cleared', async ({ page, context }) => {
  const section = page.locator('#sesiones')
  await section.getByText('Elegir o cambiar días', { exact: true }).click()
  const selects = section.getByRole('combobox')
  for (let index = 0; index < 7; index++) await selects.nth(index).selectOption('')
  await selects.nth(0).selectOption('mancuernas')
  await selects.nth(3).selectOption('gimnasio')
  await section.getByRole('button', { name: 'Guardar días y sesiones' }).click()
  await expect(section.getByRole('status')).toHaveText('Planificación guardada en tu cuenta.')
  await page.reload()
  await expect(section.getByRole('link', { name: /Lunes.*En casa/ })).toHaveAttribute('href', '/comunidad/ejercicios/sesiones#mancuernas')
  await section.getByRole('link', { name: /Jueves.*En el gimnasio/ }).click()
  await expect(page.getByRole('heading', { name: 'En el gimnasio', exact: true })).toBeInViewport()
  const image = page.locator('section#gimnasio figure img').first()
  await expect.poll(() => image.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await fixtureSession(context, 'paid')
  await page.goto('/comunidad/mi-semana')
  await expect(section.getByRole('link', { name: /Abrir sesión/ })).toHaveCount(0)
  await fixtureSession(context, 'free')
  await page.reload()
  await expect(section.getByRole('link', { name: /Abrir sesión/ })).toHaveCount(2)
  await section.getByText('Elegir o cambiar días', { exact: true }).click()
  await selects.nth(0).selectOption('')
  await section.getByRole('button', { name: 'Guardar días y sesiones' }).click()
  await expect(section.getByRole('status')).toHaveText('Planificación guardada en tu cuenta.')
  await page.reload()
  await expect(section.getByRole('link', { name: /Abrir sesión/ })).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('failed save keeps changes visible and missing calendar keeps PDF available', async ({ page, request }) => {
  const section = page.locator('#sesiones')
  await section.getByText('Elegir o cambiar días', { exact: true }).click()
  const select = section.getByRole('combobox').nth(2)
  await select.selectOption('mancuernas')
  await request.post('http://127.0.0.1:54329/__workout-failure', { data: { mode: 'writes' } })
  await section.getByRole('button', { name: 'Guardar días y sesiones' }).click()
  await expect(section.getByRole('status')).toContainText('No se ha podido guardar')
  await expect(select).toHaveValue('mancuernas')
  await expect(section.getByRole('link', { name: /Miércoles.*Abrir sesión/ })).toHaveCount(0)
  await request.post('http://127.0.0.1:54329/__workout-failure', { data: { mode: 'all' } })
  await page.reload()
  await expect(section.getByRole('status')).toContainText('El calendario no está disponible')
  await expect(section.getByRole('link', { name: 'Abrir planificador PDF', exact: true })).toBeVisible()
  await expect(section.getByRole('combobox')).toHaveCount(0)
  await request.post('http://127.0.0.1:54329/__workout-failure', { data: { mode: '' } })
})
